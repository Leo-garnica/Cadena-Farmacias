test('teclado: salto de contenido, foco visible, tabs, foco contenido y retorno', async ({ page }) => {
  await page.goto('/inventario')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Saltar al contenido' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('#main-content')).toBeFocused()
  const opener = page.getByRole('link', { name: /^Ver detalle de/ }).first()
  await opener.focus()
  await expect(opener).toHaveCSS('outline-style', 'solid')
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('heading', { name: 'Detalle de inventario' })).toBeFocused()
  await dialog.getByRole('tab', { name: 'Producto', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(dialog.getByRole('tab', { name: 'Lote asociado' })).toHaveAttribute('aria-selected', 'true')
  for (let step = 0; step < 8; step++) {
    await page.keyboard.press('Tab')
    expect(await dialog.evaluate((element) => element.contains(document.activeElement))).toBe(true)
  }
  await page.keyboard.press('Escape')
  await expect(opener).toBeFocused()
})

test('navegación local sin solicitudes externas ni errores de consola', async ({ page }) => {
  const requests: string[] = []
  const errors: string[] = []
  page.on('request', (request) => { if (!request.url().startsWith('http://127.0.0.1:5173')) requests.push(request.url()) })
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/inventario')
  await page.getByRole('link', { name: /^Ver detalle de/ }).first().click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('tab', { name: 'Lote asociado' }).click()
  await page.keyboard.press('Escape')
  await page.getByLabel('Sucursal', { exact: true }).selectOption('3')
  await expect(page.getByRole('heading', { name: 'Existencias de Valle' })).toBeVisible()
  expect(requests).toEqual([])
  expect(errors).toEqual([])
})
