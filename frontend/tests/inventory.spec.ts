import { test, expect } from '@playwright/test'

test('recorrido completo: sucursal, búsqueda, orden, paginación, detalle, Escape y Atrás', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Inventario', exact: true })).toBeVisible()
  await expect(page.getByText('Datos simulados · Solo consulta', { exact: true })).toBeVisible()
  await page.getByLabel('Sucursal', { exact: true }).selectOption('2')
  await page.getByLabel('Buscar producto', { exact: true }).fill('10')
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
  await page.getByLabel('Ordenar por').selectOption('codigo-asc')
  await expect(page).toHaveURL(/orden=codigo-asc/)
  const summary = await page.getByRole('region', { name: 'Resumen del conjunto filtrado' }).innerText()
  await page.getByRole('link', { name: 'Página siguiente' }).click()
  await expect(page).toHaveURL(/pagina=2/)
  const origin = page.url()
  await expect(page.getByRole('region', { name: 'Resumen del conjunto filtrado' })).toHaveText(summary, { useInnerText: true })
  const opener = page.getByRole('link', { name: 'Ver detalle de Omeprazol 20 mg', exact: true })
  await opener.focus()
  await page.keyboard.press('Enter')
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(page).toHaveURL(/inventario\/2\/1009/)
  await dialog.getByRole('tab', { name: 'Lote asociado' }).click()
  await expect(page).toHaveURL(/tab=lote/)
  await expect(dialog.getByRole('tabpanel')).toContainText('VF-26-009')
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(page).toHaveURL(origin)
  await expect(opener).toBeFocused()
  await opener.click()
  await expect(dialog).toBeVisible()
  await page.goBack()
  await expect(dialog).toBeHidden()
  await expect(page).toHaveURL(origin)
  await expect(page.getByLabel('Buscar producto', { exact: true })).toHaveValue('10')
  await expect(page.getByLabel('Sucursal', { exact: true })).toHaveValue('2')
  await page.goForward()
  await expect(dialog).toBeVisible()
})

test('categoría, búsqueda y orden persisten al recargar y limpiar conserva sucursal', async ({ page }) => {
  await page.goto('/inventario?farmacia=2&q=10&categoria=6&orden=nombre-desc&pagina=1')
  await expect(page.locator('tbody tr')).toHaveCount(4)
  await expect(page.getByLabel('Categoría', { exact: true })).toHaveValue('6')
  await page.reload()
  await expect(page.getByLabel('Categoría', { exact: true })).toHaveValue('6')
  await expect(page.getByLabel('Buscar producto', { exact: true })).toHaveValue('10')
  await expect(page.getByLabel('Ordenar por')).toHaveValue('nombre-desc')
  await page.getByRole('link', { name: 'Limpiar filtros', exact: true }).click()
  await expect(page.getByLabel('Sucursal', { exact: true })).toHaveValue('2')
  await expect(page.getByLabel('Buscar producto', { exact: true })).toHaveValue('')
  await expect(page.locator('tbody tr')).toHaveCount(8)
})

test('acceso directo al detalle y recarga conservan sucursal y pestaña', async ({ page }) => {
  await page.goto('/inventario/3/1001?tab=lote')
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('tab', { name: 'Lote asociado' })).toHaveAttribute('aria-selected', 'true')
  await expect(dialog).toContainText('Sucursal Valle')
  await page.reload()
  await expect(dialog.getByRole('tab', { name: 'Lote asociado' })).toHaveAttribute('aria-selected', 'true')
  await dialog.getByRole('button', { name: 'Cerrar panel' }).click()
  await expect(page).toHaveURL(/\/inventario\?farmacia=3/)
  await expect(page.getByRole('heading', { name: 'Inventario', exact: true })).toBeFocused()
})

