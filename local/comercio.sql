CREATE TABLE IF NOT EXISTS commerce.pedidos (
  id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  operacion uuid NOT NULL UNIQUE,
  solicitud text NOT NULL,
  cliente_sub uuid NOT NULL,
  cliente_id integer NOT NULL REFERENCES public.cliente,
  farmacia integer NOT NULL REFERENCES public.farmacia,
  modalidad text NOT NULL CHECK (modalidad IN ('retiro', 'envio')),
  estado text NOT NULL CONSTRAINT commerce_pedido_estado CHECK (estado IN
    ('confirmado', 'en_preparacion', 'listo', 'en_camino', 'entregado', 'cancelado', 'devuelto')),
  fecha timestamptz NOT NULL DEFAULT clock_timestamp(),
  vence timestamptz,
  total_centavos bigint NOT NULL CHECK (total_centavos >= 0),
  envio_centavos integer NOT NULL CHECK (envio_centavos >= 0),
  asignado uuid,
  zona integer REFERENCES commerce.zonas,
  direccion text,
  codigo_retiro text,
  venta integer UNIQUE REFERENCES public.venta,
  CHECK ((modalidad = 'retiro' AND codigo_retiro IS NOT NULL AND zona IS NULL AND direccion IS NULL)
      OR (modalidad = 'envio' AND codigo_retiro IS NULL AND zona IS NOT NULL AND direccion IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS comercio_pedidos_farmacia_estado ON commerce.pedidos (farmacia, estado, fecha);
CREATE INDEX IF NOT EXISTS comercio_pedidos_cliente ON commerce.pedidos (cliente_sub, fecha DESC);

CREATE TABLE IF NOT EXISTS commerce.pedido_lineas (
  pedido integer NOT NULL REFERENCES commerce.pedidos,
  codigo integer NOT NULL REFERENCES public.producto,
  nombre text NOT NULL,
  cantidad integer NOT NULL CHECK (cantidad > 0),
  precio_centavos bigint NOT NULL CHECK (precio_centavos >= 0),
  PRIMARY KEY (pedido, codigo)
);
CREATE INDEX IF NOT EXISTS comercio_reserva_producto ON commerce.pedido_lineas (codigo);

CREATE TABLE IF NOT EXISTS commerce.eventos (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  pedido integer NOT NULL REFERENCES commerce.pedidos,
  actor uuid,
  accion text NOT NULL,
  motivo text,
  fecha timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE IF NOT EXISTS commerce.ventas (
  id integer PRIMARY KEY REFERENCES public.venta,
  farmacia integer NOT NULL REFERENCES public.farmacia,
  empleado_sub uuid NOT NULL,
  canal text NOT NULL CHECK (canal IN ('online', 'presencial')),
  fecha timestamptz NOT NULL DEFAULT clock_timestamp(),
  total_centavos bigint NOT NULL CHECK (total_centavos >= 0),
  revertida timestamptz,
  pedido integer UNIQUE REFERENCES commerce.pedidos,
  operacion uuid UNIQUE,
  solicitud text,
  CHECK ((canal = 'online' AND pedido IS NOT NULL AND operacion IS NULL)
      OR (canal = 'presencial' AND pedido IS NULL AND operacion IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS comercio_ventas_periodo ON commerce.ventas (farmacia, fecha DESC);

CREATE TABLE IF NOT EXISTS commerce.venta_lineas (
  venta integer NOT NULL REFERENCES commerce.ventas,
  codigo integer NOT NULL REFERENCES public.producto,
  nombre text NOT NULL,
  cantidad integer NOT NULL CHECK (cantidad > 0),
  precio_centavos bigint NOT NULL CHECK (precio_centavos >= 0),
  lote integer REFERENCES public.lote,
  PRIMARY KEY (venta, codigo)
);

