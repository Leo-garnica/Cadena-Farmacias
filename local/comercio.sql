CREATE TABLE IF NOT EXISTS commerce.zonas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farmacia integer NOT NULL REFERENCES public.farmacia,
  nombre text NOT NULL,
  envio_centavos integer NOT NULL CHECK (envio_centavos >= 0),
  plazo text NOT NULL,
  UNIQUE (farmacia, nombre)
);
