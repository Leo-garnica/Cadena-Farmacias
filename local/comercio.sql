CREATE TABLE IF NOT EXISTS commerce.movimientos (
  id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  farmacia integer NOT NULL REFERENCES public.farmacia,
  codigo integer NOT NULL REFERENCES public.producto,
  cantidad integer NOT NULL CHECK (cantidad <> 0),
  motivo text NOT NULL,
  fecha timestamptz NOT NULL DEFAULT clock_timestamp(),
  actor uuid NOT NULL,
  venta integer REFERENCES commerce.ventas,
  operacion uuid UNIQUE,
  solicitud text
);
CREATE INDEX IF NOT EXISTS comercio_movimientos_periodo ON commerce.movimientos (farmacia, fecha DESC);

CREATE TABLE IF NOT EXISTS commerce.cliente_sucursal (
  farmacia integer NOT NULL REFERENCES public.farmacia,
  cliente integer NOT NULL REFERENCES public.cliente,
  PRIMARY KEY (farmacia, cliente)
);
